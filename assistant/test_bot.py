def run_evaluation():
    output_file = "results.txt"
    total = len(QUESTIONS)
    
    print(f"🚀 بدء اختبار الموديل بـ {total} سؤال...")
    print(f"📁 سيتم حفظ النتائج أولاً بأول في ملف: {output_file}\n")
    
    with open(output_file, "w", encoding="utf-8") as f:
        f.write("=== تقرير اختبار شات بوت SUTech Transport (100 سؤال) ===\n\n")
        
        for idx, q in enumerate(QUESTIONS, start=1):
            print(f"[{idx}/{total}] جاري سؤال: {q}")
            try:
                res = chat_endpoint(ChatRequest(question=q))
                answer = res.get("response", "لا يوجد رد").strip()
                status = res.get("status", "unknown")
            except Exception as e:
                answer = f"خطأ أثناء التشغيل: {str(e)}"
                status = "error"
            
            # كتابة النتيجة في الملف فوراً
            f.write(f"س{idx}: {q}\n")
            f.write(f"الحالة: {status}\n")
            f.write(f"ج{idx}: {answer}\n")
            f.write("-" * 60 + "\n")
            f.flush()  # حفظ لحظي في الملف
            
            # انتظار 4 ثواني لتجنب حظر الـ Rate Limit من جوجل
            if idx < total:
                time.sleep(4)
                
    print("\n✅ تم الانتهاء من الـ 100 سؤال بنجاح! افتح ملف results.txt وابعته للتقييم.")

if __name__ == "__main__":
    run_evaluation()