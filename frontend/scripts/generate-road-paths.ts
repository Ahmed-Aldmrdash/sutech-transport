/**
 * Turns each line's waypoints (src/features/tracking/mock-geo.ts) into a route along the real
 * streets, using the public OSRM demo server on OpenStreetMap data, and writes
 * src/features/tracking/mock-road-paths.ts. Run with `npm run road-paths` on a machine with
 * internet access; the app itself never calls a routing service. Mock data only: the real bus
 * sends its own GPS.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { LINE_WAYPOINTS, mockWaypointsOf } from "../src/features/tracking/mock-geo";

const OSRM = "https://router.project-osrm.org/route/v1/driving";
/** Points closer than this to the simplified line are dropped (about 25 m). */
const TOLERANCE_DEGREES = 0.00025;
const DECIMALS = 5;
/** Be polite to the free demo server. */
const PAUSE_MS = 1100;

type Point = readonly [number, number];

function distanceToSegment(point: Point, a: Point, b: Point): number {
  const [x, y] = point;
  const [x1, y1] = a;
  const [x2, y2] = b;
  const dx = x2 - x1;
  const dy = y2 - y1;
  const lengthSquared = dx * dx + dy * dy;
  const t =
    lengthSquared === 0
      ? 0
      : Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / lengthSquared));
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}

/** Douglas–Peucker: keeps the bends, drops the straight runs. */
function simplify(points: readonly Point[]): Point[] {
  if (points.length < 3) return [...points];
  const first = points[0] as Point;
  const last = points.at(-1) as Point;
  let farthest = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i += 1) {
    const distance = distanceToSegment(points[i] as Point, first, last);
    if (distance > farthest) {
      farthest = distance;
      index = i;
    }
  }
  if (farthest <= TOLERANCE_DEGREES) return [first, last];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}

const round = (value: number) => Number(value.toFixed(DECIMALS));

async function roadPathOf(lineId: string): Promise<Point[]> {
  const coordinates = mockWaypointsOf(lineId)
    .map((point) => `${point.lng},${point.lat}`)
    .join(";");
  const response = await fetch(`${OSRM}/${coordinates}?overview=full&geometries=geojson`);
  if (!response.ok) throw new Error(`${lineId}: OSRM answered ${response.status}`);
  const body = (await response.json()) as {
    code: string;
    routes?: { geometry: { coordinates: [number, number][] } }[];
  };
  const route = body.routes?.[0];
  if (body.code !== "Ok" || !route) throw new Error(`${lineId}: no route (${body.code})`);
  const latLng = route.geometry.coordinates.map(([lng, lat]): Point => [lat, lng]);
  return simplify(latLng).map(([lat, lng]): Point => [round(lat), round(lng)]);
}

const root = path.resolve(import.meta.dirname, "..");
const lines: string[] = [];
for (const lineId of Object.keys(LINE_WAYPOINTS)) {
  const points = await roadPathOf(lineId);
  lines.push(`  ${lineId}: ${JSON.stringify(points)},`);
  console.log(`${lineId}: ${points.length} points`);
  await new Promise((resolve) => setTimeout(resolve, PAUSE_MS));
}

writeFileSync(
  path.join(root, "src/features/tracking/mock-road-paths.ts"),
  `// Generated by \`npm run road-paths\` (scripts/generate-road-paths.ts). Do not edit by hand.
// Each line's demo route along the streets, from OpenStreetMap through OSRM, simplified.
// Static demo data: the app never calls a routing service. The real bus sends its own GPS.

export const ROAD_PATHS: Readonly<Record<string, readonly (readonly [number, number])[]>> = {
${lines.join("\n")}
};
`,
);
console.log("Wrote src/features/tracking/mock-road-paths.ts");
